const MESSAGES: Record<Locale, Record<MessageKey, string>> = { zh, en, fr, ru };

const VALID = new Set<Locale>(["zh", "en", "fr", "ru"]);

function detectLocale(): Locale {
  try {
    const stored = window.localStorage.getItem("scoreomr.locale");
    if (stored && VALID.has(stored as Locale)) return stored as Locale;
  } catch {
    // ignore
  }
  // The product is Chinese-first; the switch is explicit and persisted.
  return "zh";
}

let currentLocale: Locale = detectLocale();

export function getLocale(): Locale {
  return currentLocale;
}

export function getLocaleTag(locale: Locale = currentLocale): string {
  return TAGS[locale];
}

export function translate(locale: Locale, key: MessageKey, vars?: Vars): string {
  const template = MESSAGES[locale][key] ?? MESSAGES.zh[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, vars?: Vars) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    currentLocale = detectLocale();
    return currentLocale;
  });

  useEffect(() => {
    currentLocale = locale;
    document.documentElement.lang = getLocaleTag(locale);
    try {
      window.localStorage.setItem("scoreomr.locale", locale);
    } catch {
      // ignore
    }
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    currentLocale = next;
    setLocaleState(next);
  }, []);

  const t = useCallback(
    (key: MessageKey, vars?: Vars) => translate(locale, key, vars),
    [locale],
  );

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export function errorMessage(error: unknown, t: I18nValue["t"]): string {
  if (error && typeof error === "object" && "code" in error) {
    const code = String((error as { code?: unknown }).code || "");
    const key = `error.${code}` as MessageKey;
    if (key in MESSAGES.zh) return t(key);
  }
  if (error instanceof Error && error.message) return error.message;
  return t("error.generic");
}

export const languageName = (locale: Locale) =>
  LOCALES.find((item) => item.id === locale)?.label ?? locale;


